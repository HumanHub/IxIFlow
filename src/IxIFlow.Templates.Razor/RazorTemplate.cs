using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;

namespace IxIFlow.Templates.Razor;

/// <summary>
/// The base class of a compiled Razor template: the template's code reads its model through <see cref="Model"/> and
/// writes through the methods Razor generates calls to. In an HTML template, every value is HTML-encoded unless the
/// template wraps it in <see cref="Raw"/>.
/// </summary>
/// <typeparam name="TModel">The model type the template was compiled against.</typeparam>
public abstract class RazorTemplate<TModel>
{
    private readonly StringBuilder _output = new();
    private TemplateFormat _format;
    private string? _attributeSuffix;

    /// <summary>The model the template renders.</summary>
    public TModel Model { get; private set; } = default!;

    /// <summary>The culture values are formatted for; also the current culture while the template runs.</summary>
    public CultureInfo Culture { get; private set; } = CultureInfo.InvariantCulture;

    /// <summary>The template's body, generated by Razor.</summary>
    public abstract Task ExecuteAsync();

    /// <summary>Text written without encoding, for HTML the template means to write as it is.</summary>
    public static RawText Raw(string? value) => new(value);

    protected void WriteLiteral(string? literal) => _output.Append(literal);

    protected void Write(object? value)
    {
        switch (value)
        {
            case null:
                return;
            case RawText raw:
                _output.Append(raw.Value);
                return;
            case IFormattable formattable:
                Write(formattable.ToString(null, Culture));
                return;
            default:
                Write(value.ToString());
                return;
        }
    }

    protected void Write(string? value)
    {
        if (string.IsNullOrEmpty(value))
            return;
        _output.Append(_format == TemplateFormat.Html ? HtmlEncoder.Default.Encode(value) : value);
    }

    protected void BeginWriteAttribute(string name, string prefix, int prefixOffset, string suffix, int suffixOffset,
        int attributeValuesCount)
    {
        _attributeSuffix = suffix;
        WriteLiteral(prefix);
    }

    protected void WriteAttributeValue(string prefix, int prefixOffset, object? value, int valueOffset, int valueLength,
        bool isLiteral)
    {
        WriteLiteral(prefix);
        if (isLiteral)
            WriteLiteral(value?.ToString());
        else
            Write(value);
    }

    protected void EndWriteAttribute()
    {
        WriteLiteral(_attributeSuffix);
        _attributeSuffix = null;
    }

    internal async Task<string> RenderAsync(TModel model, CultureInfo culture, TemplateFormat format)
    {
        Model = model;
        Culture = culture;
        _format = format;
        var current = CultureInfo.CurrentCulture;
        var currentUi = CultureInfo.CurrentUICulture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        try
        {
            await ExecuteAsync();
            return _output.ToString();
        }
        finally
        {
            CultureInfo.CurrentCulture = current;
            CultureInfo.CurrentUICulture = currentUi;
        }
    }
}

/// <summary>Text a template writes without encoding; see <see cref="RazorTemplate{TModel}.Raw"/>.</summary>
public sealed class RawText(string? value)
{
    public string? Value { get; } = value;

    public override string? ToString() => Value;
}
