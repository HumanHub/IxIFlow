using System.Globalization;
using System.Text;
using IxIFlow.Dsl.Compilation;
using IxIFlow.Dsl.Documents;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using YamlDotNet.Core;
using YamlDotNet.RepresentationModel;

namespace IxIFlow.Generators;

/// <summary>Options for translating a standalone authored activity document.</summary>
public sealed class ActivitySourceOptions
{
    /// <summary>Signals that activity source translation should stop.</summary>
    public CancellationToken CancellationToken { get; init; }

    // Populated by standalone compilation after binding the generated properties
    // with the authored declarations, imports and prepared references in scope.
    internal IReadOnlyDictionary<string, ITypeSymbol>? MemberTypes { get; init; }
}

/// <summary>Translates an activity document into one concrete asynchronous activity.</summary>
public static class ActivitySourceTranslator
{
    public static string Translate(ActivityDocument document, string sourceText, string sourcePath,
        ActivitySourceOptions? options = null)
    {
        var validation = ActivityDocumentValidator.Validate(document, sourceText);

        if (!validation.IsValid)
        {
            var error = validation.Diagnostics.First(item => item.Severity == WorkflowDiagnosticSeverity.Error);
            var location = DocumentModel.GetLocation(document, error.Path);

            throw new WorkflowSourceException(error.Code + ": " + error.Message, sourcePath, location.Line, location.Column);
        }

        var identity = new ActivityPackageIdentity(document.Activity.Key, document.Activity.Version);
        var sourceLines = sourceText.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
        var stream = new YamlStream();
        using var reader = new StringReader(sourceText);
        stream.Load(reader);
        var root = (YamlMappingNode)stream.Documents[0].RootNode;
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        void Line(string text) => source.Append(text).Append('\n');

        void Locate(string path, string text, int offset = 0, int length = 1)
        {
            var location = DocumentModel.GetLocation(document, path);

            if (length > 1)
            {
                if (location.Line <= sourceLines.Length && location.Column <= sourceLines[location.Line - 1].Length &&
                    sourceLines[location.Line - 1][location.Column - 1] is '\'' or '"')
                    location = location with { Column = location.Column + 1 };
            }

            Line(
                $"#line ({location.Line}, {location.Column}) - ({location.Line}, {location.Column + Math.Max(1, length)}) {offset + 1} {Literal(sourcePath)}");

            Line(text);
            Line("#line default");
        }

        foreach (var name in new[] { "System", "System.Collections.Generic", "System.Threading", "System.Threading.Tasks", "IxIFlow.Core" })
            Line("using " + name + ";");

        for (var index = 0; index < document.Usings.Count; index++)
            Locate("usings[" + index + "]", "using " + document.Usings[index] + ";", 6, document.Usings[index].Length);

        Line("[assembly: global::System.Reflection.AssemblyVersion(" + Literal(identity.AssemblyVersion) + ")]");
        Line("[assembly: global::System.Reflection.AssemblyInformationalVersion(" + Literal(identity.InformationalVersion) + ")]");
        Line("namespace " + identity.Namespace + ";");
        var header = document.Activity;
        var metadata = new List<string> { "Version = " + Literal(identity.ActivityVersion) };

        foreach (var pair in new[]
                     { ("Name", header.Name), ("Category", header.Category), ("Icon", header.Icon), ("Designer", header.Designer) })
            if (pair.Item2 != null)
                metadata.Add(pair.Item1 + " = " + Literal(pair.Item2));

        Locate("activity.key",
            "[global::IxIFlow.ActivitySdk.WorkflowActivity(" + Literal(header.Key) + ", " + string.Join(", ", metadata) + ")]");

        if (header.Description != null)
            Locate("activity.description", "[global::System.ComponentModel.Description(" + Literal(header.Description) + ")]");

        foreach (var type in header.RequiresScopes)
            Locate("activity.requiresScopes", "[global::IxIFlow.Core.RequiresScope<" + type + ">]");

        if (header.Concurrency != null)
            Locate("activity.concurrency",
                "[global::IxIFlow.Core.ScopeConcurrency(global::IxIFlow.Core.ScopeConcurrency." +
                (header.Concurrency == "shared" ? "Shared" : "Serialized") + ")]");

        if (header.Threading != null)
            Locate("activity.threading",
                "[global::IxIFlow.Core.ScopeThreading(global::IxIFlow.Core.ScopeThreading." +
                (header.Threading == "threadAffine" ? "ThreadAffine" : "AnyThread") + ")]");

        Locate(header.Scope == null ? "activity.key" : "activity.scope", "public sealed class " + identity.ClassName + " : " +
            (header.Scope == null ? "global::IxIFlow.Core.IAsyncActivity" : "global::IxIFlow.Core.IScopeActivity<" + header.Scope + ">"));

        Line("{");

        foreach (var direction in new[]
                 {
                     ("input", "ActivityInput", document.Input), ("output", "ActivityOutput", document.Output),
                     ("inOut", "ActivityInputOutput", document.InOut)
                 })
        foreach (var pair in direction.Item3)
        {
            options?.CancellationToken.ThrowIfCancellationRequested();
            var member = pair.Value;
            var path = direction.Item1 + "." + pair.Key;
            ITypeSymbol? boundType = null;

            if (options?.MemberTypes is { } types && (!types.TryGetValue(pair.Key, out boundType) || boundType == null))
                throw new InvalidOperationException("Bound activity member '" + path + "' has no generated property");

            Line("[global::IxIFlow.ActivitySdk." + direction.Item2 + "]");

            if (member.Required)
                Locate(path + ".required", "[global::System.ComponentModel.DataAnnotations.Required]");

            if (member.HasDefault())
            {
                if (!ActivityDefaultValue.TryGetText(member, out var text, boundType))
                {
                    var location = DocumentModel.GetLocation(document, path + ".default");

                    throw new WorkflowSourceException("ACTD010: Default must be a supported finite scalar value", sourcePath, location.Line,
                        location.Column);
                }

                Locate(path + ".default", "[global::System.ComponentModel.DefaultValue(" + Default(member, text, boundType) + ")]");
            }

            var display = new List<string>();

            if (member.Label != null)
                display.Add("Name = " + Literal(member.Label));

            if (member.Help != null)
                display.Add("Description = " + Literal(member.Help));

            if (display.Count > 0)
                Locate(path + (member.Label != null ? ".label" : ".help"),
                    "[global::System.ComponentModel.DataAnnotations.Display(" + string.Join(", ", display) + ")]");

            if (member.Control != null)
                Locate(path + ".control", "[global::System.ComponentModel.DataAnnotations.UIHint(" + Literal(member.Control) + ")]");

            Locate(path + ".type", "public " + member.Type + " " + pair.Key + " { get; set; } = default!;", 7, member.Type.Length);
        }

        Line("#pragma warning disable CS1998");

        Line(header.Scope == null
            ? "public async global::System.Threading.Tasks.Task ExecuteAsync(global::IxIFlow.Core.IActivityContext context, global::System.Threading.CancellationToken cancellationToken = default)"
            : "public async global::System.Threading.Tasks.Task<" + header.Scope +
            "> OpenAsync(global::IxIFlow.Core.ScopeOpening opening, global::IxIFlow.Core.IScopeContext context, global::System.Threading.CancellationToken cancellationToken)");

        Line("{");
        Block("body", document.Body);
        Line("}");
        Line("#pragma warning restore CS1998");

        if (document.Declarations != null)
            Block("declarations", document.Declarations);

        Line("}");

        return source.ToString();

        void Block(string member, string value)
        {
            options?.CancellationToken.ThrowIfCancellationRequested();
            var pair = root.Children.FirstOrDefault(pair => pair.Key is YamlScalarNode key && key.Value == member);

            if (pair.Value is not YamlScalarNode { Style: ScalarStyle.Literal } scalar || scalar.Value != value)
            {
                var location = DocumentModel.GetLocation(document, member);

                throw new WorkflowSourceException("The document's " + member + " must match its authored literal block", sourcePath,
                    location.Line, location.Column);
            }

            var start = (int)scalar.Start.Line;

            // The parser's scalar bounds exclude less-indented YAML comments and retain
            // the physical content indentation, independently of the chomping indicator.
            var contentStart = SourceText.From(sourceText).Lines[start - 1].EndIncludingLineBreak;

            var code = sourceText.Substring(contentStart, (int)scalar.End.Index - contentStart)
                .Replace("\r\n", "\n").Replace('\r', '\n');

            ValidateBlock(member, code, sourcePath, start + 1);
            Line("#line " + (start + 1).ToString(CultureInfo.InvariantCulture) + " " + Literal(sourcePath));
            source.Append(code);

            if (!code.EndsWith("\n", StringComparison.Ordinal))
                Line("");

            Line("#line default");
        }
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static void ValidateBlock(string member, string code, string sourcePath, int firstLine)
    {
        var prefix = member == "body" ? "{\n" : "class __Activity\n{\n";
        var text = SourceText.From(prefix + code + "\n}");
        var options = new CSharpParseOptions(LanguageVersion.CSharp14);

        // Keep the compilation unit's EOF trivia as well as its container: parsing
        // a detached statement drops trailing unterminated comments from diagnostics.
        var syntax = (CompilationUnitSyntax)CSharpSyntaxTree.ParseText(text, options).GetRoot();

        void Refuse(int position, string message)
        {
            // Errors in a synthesized delimiter point to the last authored token.
            var offset = Math.Max(0, Math.Min(code.Length, position - prefix.Length));

            if (offset == code.Length)
                offset = syntax.DescendantTokens().Where(token => !token.IsMissing && token.Span.Length > 0 &&
                        token.SpanStart >= prefix.Length && token.Span.End <= prefix.Length + code.Length)
                    .Select(token => token.SpanStart - prefix.Length).DefaultIfEmpty(code.TakeWhile(char.IsWhiteSpace).Count()).Last();

            var location = SourceText.From(code).Lines.GetLinePosition(offset);

            throw new WorkflowSourceException(message, sourcePath, firstLine + location.Line, location.Character + 1);
        }

        var directive = syntax.DescendantTrivia(descendIntoTrivia: true)
            .FirstOrDefault(trivia => trivia.GetStructure() is DirectiveTriviaSyntax);

        if (directive.RawKind != 0)
            Refuse(directive.SpanStart, "Directives are not permitted in authored " + member);

        SyntaxNode? container = member == "body"
            ? (syntax.Members.FirstOrDefault() as GlobalStatementSyntax)?.Statement as BlockSyntax
            : syntax.Members.FirstOrDefault() as ClassDeclarationSyntax;

        var closingBrace = container switch
        {
            BlockSyntax block => block.CloseBraceToken,
            ClassDeclarationSyntax declaration => declaration.CloseBraceToken,
            _ => default
        };

        if (closingBrace.RawKind != 0 && !closingBrace.IsMissing && closingBrace.SpanStart < prefix.Length + code.Length)
            Refuse(closingBrace.SpanStart, "Authored " + member + " cannot close its generated container");

        // Prefer the authored error over recovery errors on synthesized delimiters
        // (for example, an unterminated comment also leaves the outer brace missing).
        var errors = syntax.GetDiagnostics().Where(item => item.Severity == DiagnosticSeverity.Error).ToArray();

        var error = syntax.DescendantTrivia(descendIntoTrivia: true).SelectMany(trivia => trivia.GetDiagnostics())
                .FirstOrDefault(item => item.Severity == DiagnosticSeverity.Error && item.Location.SourceSpan.Start >= prefix.Length &&
                    item.Location.SourceSpan.Start < prefix.Length + code.Length) ??
            errors.FirstOrDefault(item => item.Location.SourceSpan.Start >= prefix.Length &&
                item.Location.SourceSpan.Start < prefix.Length + code.Length) ?? errors.FirstOrDefault();

        if (error != null)
            Refuse(error.Location.SourceSpan.Start, error.GetMessage(CultureInfo.InvariantCulture));

        if (container == null || syntax.Members.Count != 1 ||
            closingBrace.IsMissing || closingBrace.SpanStart != text.Length - 1 ||
            syntax.DescendantTrivia(descendIntoTrivia: true).Any(trivia => trivia.IsKind(SyntaxKind.SkippedTokensTrivia)))
            Refuse(prefix.Length, "Authored " + member + " must be fully contained " + (member == "body" ? "statements" : "class members"));
    }

    private static string Default(ActivityMemberDocument member, string text, ITypeSymbol? boundType) => member.Default switch
    {
        null => "null",
        string value when boundType?.SpecialType == SpecialType.System_String ||
            boundType == null && member.Type is "string" or "string?" or "global::System.String" => Literal(value),
        bool flag when boundType?.SpecialType == SpecialType.System_Boolean ||
            boundType == null && member.Type is "bool" or "global::System.Boolean" => flag ? "true" : "false",
        _ => "typeof(" + ActivityDefaultValue.ConversionType(member.Type, boundType) + "), " + Literal(text)
    };
}